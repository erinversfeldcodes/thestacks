defmodule Stacks.Feeds do
  @moduledoc """
  Context for generating Atom 1.0 feeds for public bookshelves.

  Each platform-visible bookshelf can have an Atom feed that RSS readers can
  subscribe to. Feeds are regenerated by `RegenerateFeedJob` when placement
  events fire, and served by `FeedController` with ETag caching.
  """

  alias Stacks.Shelving

  require Logger

  @atom_ns "http://www.w3.org/2005/Atom"

  @doc """
  Generates an Atom 1.0 XML feed for the given user's bookshelf.

  Only bookshelves with `visibility: "platform"` are eligible.
  Returns `{:ok, xml_string, etag}` on success, or `{:error, reason}` on failure.

  The ETag is an MD5 hash of the generated XML, hex-encoded in lowercase.
  """
  @spec generate_atom(binary(), String.t()) ::
          {:ok, String.t(), String.t()} | {:error, :not_found | :not_public}
  def generate_atom(user_id, bookshelf_name) do
    case Shelving.get_bookshelf(user_id, bookshelf_name) do
      nil ->
        {:error, :not_found}

      %{visibility: visibility} when visibility != "platform" ->
        {:error, :not_public}

      bookshelf ->
        placements = Shelving.get_bookshelf_books(user_id, bookshelf_name)
        xml = build_atom_xml(bookshelf, placements)
        etag = compute_etag(xml)
        {:ok, xml, etag}
    end
  end

  @doc """
  Computes an ETag string from XML content.

  Uses MD5 hashing, hex-encoded in lowercase.
  """
  @spec compute_etag(String.t()) :: String.t()
  def compute_etag(xml) when is_binary(xml) do
    :crypto.hash(:md5, xml) |> Base.encode16(case: :lower)
  end

  # ── Private helpers ────────────────────────────────────────────────────────

  defp build_atom_xml(bookshelf, placements) do
    user = bookshelf.user
    display_name = user.display_name || user.email

    updated =
      placements
      |> Enum.map(& &1.placed_at)
      |> Enum.reject(&is_nil/1)
      |> Enum.max(DateTime, fn -> DateTime.utc_now() end)
      |> DateTime.to_iso8601()

    entries = Enum.map_join(placements, "\n", &build_entry(&1, bookshelf.name))

    """
    <?xml version="1.0" encoding="utf-8"?>
    <feed xmlns="#{@atom_ns}">
      <title>#{escape_xml(display_name)}'s #{humanize_bookshelf(bookshelf.name)}</title>
      <id>urn:stacks:feed:#{bookshelf.id}</id>
      <updated>#{updated}</updated>
      <author>
        <name>#{escape_xml(display_name)}</name>
      </author>
    #{entries}
    </feed>
    """
    |> String.trim()
  end

  defp build_entry(placement, bookshelf_name) do
    book = placement.book
    title = if book, do: book.title, else: "Unknown Book"

    author_name =
      if book && book.author,
        do: book.author.name,
        else: "Unknown Author"

    isbn = primary_isbn(book)

    placed_at =
      if placement.placed_at,
        do: DateTime.to_iso8601(placement.placed_at),
        else: DateTime.to_iso8601(DateTime.utc_now())

    summary =
      "#{escape_xml(title)} by #{escape_xml(author_name)} added to #{humanize_bookshelf(bookshelf_name)}"

    """
      <entry>
        <title>#{escape_xml(title)}</title>
        <id>urn:stacks:placement:#{placement.id}</id>
        <updated>#{placed_at}</updated>
        <summary>#{summary}</summary>
        <author>
          <name>#{escape_xml(author_name)}</name>
        </author>#{isbn_link(isbn)}
      </entry>\
    """
  end

  defp primary_isbn(nil), do: nil

  defp primary_isbn(book) do
    case book.editions do
      editions when is_list(editions) ->
        primary = Enum.find(editions, &(&1.is_primary == true))
        if primary, do: primary.isbn, else: nil

      _ ->
        nil
    end
  end

  defp isbn_link(nil), do: ""

  defp isbn_link(isbn) do
    "\n    <link rel=\"related\" href=\"https://openlibrary.org/isbn/#{isbn}\" />"
  end

  defp humanize_bookshelf(name) do
    name
    |> String.replace("_", " ")
    |> String.split(" ")
    |> Enum.map_join(" ", &String.capitalize/1)
  end

  defp escape_xml(nil), do: ""

  defp escape_xml(text) do
    text
    |> String.replace("&", "&amp;")
    |> String.replace("<", "&lt;")
    |> String.replace(">", "&gt;")
    |> String.replace("\"", "&quot;")
    |> String.replace("'", "&apos;")
  end
end
