defmodule Mix.Tasks.ProtoSyncInvariantsTest do
  @moduledoc """
      Three invariants the proto-sync generator holds, each previously stated
      only in a comment that has since been deleted.

      They are together because they share a subject — what the generator emits
      and what it refuses to emit — not because they are the same check. The
      first is the one with teeth.

      ## Why `skip_dbt` is not plumbing

      The flag reads like infrastructure bookkeeping and was described that way:
      opt a table out of dbt staging-model and `schema.yml` generation, for
      tables that live outside the analytics schemas.

      But two of the seven tables carrying it are `op.library_import_rows` and
      `op.feedback_entries`, and both hold free text a reader wrote — Goodreads
      reviews, private notes, messages to the owner. The warehouse has **no
      erasure path**. So for those two the flag is the thing standing between a
      reader's own words and a copy of them that no deletion request can reach.
      A staging model appearing for either is a GDPR defect, not a tidiness one.

      It holds today — none of the seven has a staging model or a `schema.yml`
      entry — and nothing asserted it. The sibling drift gate counts staging
      models and compares the number against the documentation; it has no
      opinion about WHICH tables may have one.
  """
  use ExUnit.Case, async: true

  alias Mix.Tasks.ProtoSync.Descriptor
  alias Mix.Tasks.ProtoSync.Manifest
  alias Mix.Tasks.ProtoSync.MigrationGenerator

  @repo_root Path.expand("../../../../..", __DIR__)

  @manifest Path.join(@repo_root, "proto/persisted.exs")
  @staging_dir Path.join(@repo_root, "dbt/models/staging")

  # Tables the manifest opts out of dbt generation, read from the manifest
  # rather than listed here — so a newly flagged table joins this assertion
  # without anyone remembering to come back.
  defp skip_dbt_tables do
    source = File.read!(@manifest)

    source
    # Split on the table-entry boundary, so each chunk is one table's options.
    |> String.split(~r/\n    %\{/)
    |> Enum.filter(&String.contains?(&1, "skip_dbt: true"))
    |> Enum.flat_map(fn chunk ->
      case Regex.run(~r/table_name:\s*"([a-z_]+)"/, chunk) do
        [_, table] -> [table]
        _ -> []
      end
    end)
    |> Enum.sort()
  end

  defp table_named(name) do
    table =
      @repo_root
      |> Path.join("proto/persisted.exs")
      |> Manifest.load!()
      |> Map.fetch!(:tables)
      |> Enum.find(&(&1.table_name == name))

    assert table, "no manifest table named #{inspect(name)} — this test cannot run"
    table
  end

  defp fields_for(table) do
    Descriptor.parse!(@repo_root)
    |> Descriptor.extract_fields(table.proto_file, table.proto_message)
  end

  describe "a table that opts out of dbt generation stays out of the warehouse" do
    test "the manifest is readable and some table opts out" do
      # Anti-vacuity. Every assertion below iterates the opt-out list, so an
      # empty list would make all of them trivially true — which is how this
      # file would come to pass while asserting nothing at all.
      tables = skip_dbt_tables()

      assert tables != [],
             "no table in the manifest carries `skip_dbt: true`. Either the flag was renamed " <>
               "or this parse has drifted from the manifest's shape — and until it is fixed " <>
               "every assertion in this file is vacuous."

      assert "library_import_rows" in tables,
             "the raw import rows no longer opt out of dbt. They hold the reader's Goodreads " <>
               "reviews and private notes, and the warehouse has no erasure path."

      assert "feedback_entries" in tables,
             "the beta feedback entries no longer opt out of dbt. They hold what readers wrote " <>
               "to the owner, and the warehouse has no erasure path."
    end

    test "no opt-out table has a staging model" do
      offenders =
        for table <- skip_dbt_tables(),
            path = Path.join(@staging_dir, "stg_#{table}.sql"),
            File.exists?(path),
            do: "stg_#{table}.sql"

      assert offenders == [],
             "these tables opt out of dbt generation and have a staging model anyway: " <>
               "#{inspect(offenders)}. A staging model copies the table into the warehouse, " <>
               "which has no erasure path — for the two tables here that hold a reader's own " <>
               "free text, that is a copy no deletion request can reach."
    end

    test "no opt-out table is named in the staging schema.yml" do
      # Belt to the braces above: the model file and the schema.yml entry are
      # generated by different writers, so one can appear without the other.
      schema_yml = Path.join(@staging_dir, "schema.yml") |> File.read!()

      offenders =
        for table <- skip_dbt_tables(),
            Regex.match?(~r/\bstg_#{Regex.escape(table)}\b/, schema_yml),
            do: table

      assert offenders == [],
             "these opt-out tables are named in the staging schema.yml: #{inspect(offenders)}"
    end
  end

  describe "a generated migration's filename and module name cannot disagree" do
    # The module name's exact derivation, mirrored here so the test states the
    # relationship rather than approximating it. NOT `Macro.camelize/1`: the
    # generator capitalises each underscore-separated segment and joins, then
    # appends the timestamp. My first attempt used `Macro.camelize` and no
    # timestamp, and failed against a perfectly correct generator — the third
    # over-strong assertion of this sitting, all three from inferring behaviour
    # instead of reading the implementation.
    defp expected_module(slug, timestamp) do
      camelized = slug |> to_string() |> String.split("_") |> Enum.map_join(&String.capitalize/1)
      "Core.Repo.Migrations.#{camelized}#{timestamp}"
    end

    test "the module name is the slug's camelised form plus the timestamp" do
      # Real manifest table and real descriptor fields, like the sibling
      # generator tests: a hand-built fixture omits keys the generator reads and
      # fails for reasons unrelated to the invariant.
      table = table_named("price_snapshots")
      fields = table |> fields_for() |> Enum.reject(&(&1.name == "id")) |> Enum.take(2)

      assert length(fields) == 2, "expected two extractable fields to stand in for new ones"

      timestamp = "20260728000000"
      slug = MigrationGenerator.add_columns_slug(fields, table.table_name)
      content = MigrationGenerator.generate_add_columns(table, fields, timestamp)

      assert content =~ "defmodule #{expected_module(slug, timestamp)} do",
             "the module name is no longer derived from the slug the filename uses, so a " <>
               "migration's file and its module can now disagree. Expected " <>
               "#{expected_module(slug, timestamp)}; generated:\n" <>
               String.slice(content, 0, 240)

      # No separate test for the capped-slug case. The slug caps itself and the
      # module name follows whatever it became, so there is nothing that can
      # drift independently — and the capping is already covered by the slug
      # tests in the sibling generator file, including the boundary at the
      # longest column name Postgres can produce. A second test here would have
      # needed a contrived input to reach a case already guarded.
    end
  end

  describe "generated foreign-key indexes keep a uniform shape" do
    test "non-unique, implicitly named, and built concurrently" do
      # `library_import_rows` carries two foreign keys whose indexes the
      # generator emits itself, so it exercises the branch this invariant
      # describes. (A table whose FK is already covered by a composite index has
      # its auto index suppressed — a different branch, tested elsewhere.)
      table = table_named("library_import_rows")

      content =
        MigrationGenerator.generate_create_table(table, fields_for(table), "20260728000000")

      fk_index_lines =
        content
        |> String.split("\n")
        |> Enum.filter(fn line ->
          String.contains?(line, "index(:library_import_rows, [:") and
            (String.contains?(line, "[:book_id]") or String.contains?(line, "[:placement_id]"))
        end)

      assert length(fk_index_lines) == 2,
             "expected an emitted index for each of the two foreign keys; got:\n" <>
               Enum.join(fk_index_lines, "\n")

      for line <- fk_index_lines do
        refute line =~ "unique_index",
               "a foreign-key index is unique. A foreign key is many-to-one by definition, so " <>
                 "a unique index on it silently forbids the second child row: #{line}"

        refute line =~ "name:",
               "a foreign-key index is explicitly named. These are named implicitly so the " <>
                 "generator's output stays uniform and predictable: #{line}"

        refute line =~ "concurrently: true",
               "a foreign-key index in a CREATE TABLE migration is built concurrently. It " <>
                 "cannot be: this shape is transactional, and the reason it is transactional " <>
                 "is that the table is created here — there is no concurrent session for a " <>
                 "concurrent build to spare, and opting out of the transaction to get one is " <>
                 "what let a mid-migration failure strand a created table with no " <>
                 "schema_migrations row: #{line}"
      end
    end
  end
end
